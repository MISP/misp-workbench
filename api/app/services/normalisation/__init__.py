"""Normalise and validate attributes as they are written.

The rules live in ``normalise.painless``, run by the
``misp-attributes_normalise`` ingest pipeline: the first step of the
attributes' default pipeline, so every write path goes through it (API,
pulls, feeds, bulk ingest, update_by_query) and later steps (IP extraction,
warninglists, correlations, indicators) see clean values.

Which rules run is the ``normalisation`` runtime setting, passed to the
script as params. The repo ships the pipeline with the default settings
(``opensearch/pipelines/misp-attributes_normalise.json``, generated by
``python -m app.services.normalisation``, see ``__main__``); the API re-applies the stored
settings at startup and whenever they change.
"""

import copy
import json
import logging
import pathlib
from typing import Optional

from app.defaults.runtime_settings_defaults import DEFAULT_SETTINGS

logger = logging.getLogger(__name__)

PIPELINE = "misp-attributes_normalise"
ATTRIBUTES_INDEX = "misp-attributes"
SCRIPT = (pathlib.Path(__file__).parent / "normalise.painless").read_text()
REPO_PIPELINE_FILE = (
    pathlib.Path(__file__).resolve().parents[4]
    / "opensearch"
    / "pipelines"
    / f"{PIPELINE}.json"
)
DEFAULTS = DEFAULT_SETTINGS["normalisation"]
FLAGS = (
    "enabled",
    "refang",
    "lowercase_hostnames",
    "normalise_urls",
    "strip_tracking_params",
    "canonical_ips",
    "lowercase_hashes",
    "validate_hashes",
    "validate_ips",
    "flag_reserved_ips",
)
ERROR_FIELD = "normalisation_error"

# Every issue the script can record, for docs and the UI.
ISSUES = {
    "invalid-ip": "not a valid IPv4 or IPv6 address",
    "invalid-cidr": "a CIDR whose prefix length is out of range",
    "invalid-port": "a port that isn't a number from 0 to 65535",
    "invalid-hash": "a hash of the wrong length for its type, or not hexadecimal",
    "private-ip": "a private address (RFC 1918, carrier-grade NAT, IPv6 ULA)",
    "loopback-ip": "a loopback address",
    "link-local-ip": "a link-local address",
    "documentation-ip": "a documentation address (TEST-NET, 2001:db8::/32)",
    "multicast-ip": "a multicast address",
    "reserved-ip": "a reserved or unspecified address",
}


class InvalidNormalisationConfig(ValueError):
    pass


def config(stored: Optional[dict] = None) -> dict:
    merged = copy.deepcopy(DEFAULTS)
    merged.update(stored or {})
    return merged


def validate(stored: dict) -> None:
    cfg = config(stored)
    for key in FLAGS:
        if not isinstance(cfg.get(key), bool):
            raise InvalidNormalisationConfig(f"{key} must be true or false")
    patterns = cfg.get("tracking_params")
    if not isinstance(patterns, list) or not all(
        isinstance(p, str) and p.strip() for p in patterns
    ):
        raise InvalidNormalisationConfig("tracking_params must be a list of names")


def build_pipeline(cfg: dict) -> dict:
    """The pipeline for these settings; empty (a no-op) when disabled."""
    processors = []
    if cfg["enabled"]:
        params = {k: cfg[k] for k in FLAGS if k != "enabled"}
        params["tracking_params"] = [p.strip() for p in cfg["tracking_params"]]
        processors.append(
            {
                "script": {
                    "lang": "painless",
                    "source": SCRIPT,
                    "params": params,
                    # A bug in the rules must never stop an attribute from
                    # being indexed: record it on the document instead.
                    "on_failure": [
                        {
                            "set": {
                                "field": ERROR_FIELD,
                                "value": "{{{_ingest.on_failure_message}}}",
                            }
                        }
                    ],
                }
            }
        )
    return {
        "description": (
            "Normalise and validate attribute values (refang, case, URLs, IPs, "
            "hashes). Managed by the misp-workbench API from the "
            "'normalisation' runtime settings; regenerate the repo copy with "
            "`python -m app.services.normalisation`."
        ),
        "processors": processors,
    }


def load_config() -> dict:
    from app.database import SessionLocal
    from app.services.runtime_settings import RuntimeSettings

    with SessionLocal() as db:
        return config(RuntimeSettings(db).get("normalisation"))


def sync(cfg: Optional[dict] = None) -> None:
    """Put the pipeline for the stored settings in place."""
    from app.services.opensearch import get_opensearch_client

    cfg = cfg or load_config()
    get_opensearch_client().ingest.put_pipeline(id=PIPELINE, body=build_pipeline(cfg))


def sync_quietly() -> None:
    """``sync`` that logs instead of raising (API startup)."""
    try:
        sync()
    except Exception:  # noqa: BLE001
        logger.exception("normalisation pipeline sync failed; repo defaults apply")


def reapply() -> Optional[str]:
    """Run every attribute through the pipeline again, in the background.

    An update_by_query without a script re-indexes each document through
    the default and final pipelines. Returns the OpenSearch task id.
    """
    from app.services.opensearch import get_opensearch_client

    response = get_opensearch_client().update_by_query(
        index=ATTRIBUTES_INDEX,
        body={"query": {"match_all": {}}},
        params={
            "conflicts": "proceed",
            "wait_for_completion": "false",
            "refresh": "true",
        },
    )
    return response.get("task")


def write_repo_pipeline() -> pathlib.Path:
    """Regenerate the repo's pipeline file from the script and the defaults."""
    REPO_PIPELINE_FILE.write_text(json.dumps(build_pipeline(config()), indent=4) + "\n")
    return REPO_PIPELINE_FILE
